using System.Data.Common;
using System.Text.RegularExpressions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Metadata;
using NexusAuth.Domain.AggregateRoots.OAuthClients;
using NexusAuth.Domain.AggregateRoots.Users;
using Xunit;
using AuthDbContext = NexusAuth.Persistence.DbContext;

namespace NexusAuth.Host.IntegrationTests;

/// <summary>
/// A property with a store default is omitted from INSERT whenever its value equals the property's
/// sentinel, so whether an explicit <c>false</c> survives depends on EF's sentinel conventions and on
/// the SQL default matching the model (with a <c>false</c> sentinel, <c>is_active DEFAULT true</c> wins).
/// The schema owns the defaults (production-init.sql); the EF model must always send the value.
/// </summary>
public sealed class PersistenceDefaultValueTests
{
    [Fact]
    public void No_non_key_property_relies_on_a_store_default_or_store_generated_value()
    {
        using var context = CreateContext();
        var offenders = context.Model.GetEntityTypes()
            .SelectMany(entity => entity.GetProperties())
            .Where(property => !property.IsPrimaryKey())
            // GetDefaultValue() reports the CLR default for every non-nullable column, so look for an explicit configuration.
            .Where(property => property.FindAnnotation(RelationalAnnotationNames.DefaultValue) is not null
                || property.FindAnnotation(RelationalAnnotationNames.DefaultValueSql) is not null
                // xmin-style concurrency tokens are legitimately generated by PostgreSQL.
                || (property.ValueGenerated != ValueGenerated.Never && !property.IsConcurrencyToken))
            .Select(property => $"{property.DeclaringType.DisplayName()}.{property.Name}")
            .ToArray();

        Assert.Empty(offenders);
    }

    [Fact]
    public async Task Inactive_user_insert_sends_is_active_false()
    {
        var user = User.Create("inactive.user", "Test-password-only-123!", "Inactive");
        user.UpdateScimProfile(user.Username, user.Nickname, isActive: false);

        var values = await CaptureInsertAsync(user, "users");

        Assert.Equal(false, values["is_active"]);
        Assert.Equal(false, values["is_system_account"]);
    }

    [Fact]
    public async Task Client_without_pkce_insert_sends_require_pkce_false()
    {
        var client = OAuthClient.Create("no-pkce-client", "No PKCE", requirePkce: false);

        var values = await CaptureInsertAsync(client, "oauth_clients");

        Assert.Equal(false, values["require_pkce"]);
        Assert.Equal(false, values["require_consent"]);
        Assert.Equal(true, values["is_active"]);
    }

    private static AuthDbContext CreateContext(params IInterceptor[] interceptors) =>
        new(new DbContextOptionsBuilder<AuthDbContext>()
            .UseNpgsql("Host=localhost;Database=metadata-only;Username=test;Password=test")
            .AddInterceptors(interceptors)
            .Options);

    /// <summary>
    /// Runs SaveChanges without a database: the connection open is suppressed and the INSERT
    /// command is captured and aborted, so the test sees exactly which columns EF would write.
    /// </summary>
    private static async Task<IReadOnlyDictionary<string, object?>> CaptureInsertAsync(object entity, string table)
    {
        var capture = new InsertCaptureInterceptor();
        await using var context = CreateContext(new SuppressOpenInterceptor(), capture);
        context.Database.AutoTransactionBehavior = AutoTransactionBehavior.Never;
        context.Add(entity);

        await Assert.ThrowsAnyAsync<Exception>(() => context.SaveChangesAsync());

        var command = Assert.Single(capture.Commands, item => item.Sql.Contains($"INSERT INTO nexusauth.{table} ", StringComparison.Ordinal));
        var match = Regex.Match(command.Sql, $@"INSERT INTO nexusauth\.{table} \(([^)]*)\)\s*VALUES \(([^)]*)\)");
        Assert.True(match.Success, command.Sql);
        var columns = match.Groups[1].Value.Split(',').Select(item => item.Trim().Trim('"')).ToArray();
        var parameters = match.Groups[2].Value.Split(',').Select(item => item.Trim()).ToArray();
        Assert.Equal(columns.Length, parameters.Length);
        return columns.Zip(parameters).ToDictionary(pair => pair.First, pair => command.Parameters[pair.Second]);
    }

    private sealed record CapturedCommand(string Sql, IReadOnlyDictionary<string, object?> Parameters);

    private sealed class SuppressOpenInterceptor : DbConnectionInterceptor
    {
        public override InterceptionResult ConnectionOpening(DbConnection connection, ConnectionEventData eventData, InterceptionResult result) =>
            InterceptionResult.Suppress();

        public override ValueTask<InterceptionResult> ConnectionOpeningAsync(DbConnection connection, ConnectionEventData eventData,
            InterceptionResult result, CancellationToken cancellationToken = default) => ValueTask.FromResult(InterceptionResult.Suppress());
    }

    private sealed class InsertCaptureInterceptor : DbCommandInterceptor
    {
        public List<CapturedCommand> Commands { get; } = [];

        public override InterceptionResult<DbDataReader> ReaderExecuting(DbCommand command, CommandEventData eventData,
            InterceptionResult<DbDataReader> result) => throw Capture(command);

        public override ValueTask<InterceptionResult<DbDataReader>> ReaderExecutingAsync(DbCommand command, CommandEventData eventData,
            InterceptionResult<DbDataReader> result, CancellationToken cancellationToken = default) => throw Capture(command);

        public override InterceptionResult<int> NonQueryExecuting(DbCommand command, CommandEventData eventData,
            InterceptionResult<int> result) => throw Capture(command);

        public override ValueTask<InterceptionResult<int>> NonQueryExecutingAsync(DbCommand command, CommandEventData eventData,
            InterceptionResult<int> result, CancellationToken cancellationToken = default) => throw Capture(command);

        private InvalidOperationException Capture(DbCommand command)
        {
            Commands.Add(new CapturedCommand(command.CommandText,
                command.Parameters.Cast<DbParameter>().ToDictionary(parameter => NormalizeName(parameter.ParameterName), parameter => parameter.Value)));
            return new InvalidOperationException("Command captured; execution intentionally aborted.");
        }

        // Npgsql parameters may be named "p0" while the SQL references "@p0".
        private static string NormalizeName(string name) => name.StartsWith('@') ? name : $"@{name}";
    }
}
